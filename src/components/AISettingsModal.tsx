'use client';

import React, { useState } from 'react';
import { useBusinessStore } from '@/store/useBusinessStore';
import { AISettings, Product, Resource, UsageMatrix } from '@/types';
import {
  X,
  Bot,
  Key,
  Sparkles,
  CheckCircle2,
  AlertCircle,
  Loader2,
  RefreshCw,
  Send,
  HelpCircle,
} from 'lucide-react';

interface AISettingsModalProps {
  isOpen: boolean;
  onClose: () => void;
}

const PROVIDER_DEFAULTS: { [key: string]: { baseUrl: string; model: string } } = {
  openai: {
    baseUrl: 'https://api.openai.com/v1',
    model: 'gpt-4o-mini',
  },
  groq: {
    baseUrl: 'https://api.groq.com/openai/v1',
    model: 'llama-3.3-70b-versatile',
  },
  openrouter: {
    baseUrl: 'https://openrouter.ai/api/v1',
    model: 'meta-llama/llama-3.3-70b-instruct',
  },
  deepseek: {
    baseUrl: 'https://api.deepseek.com/v1',
    model: 'deepseek-chat',
  },
  ollama: {
    baseUrl: 'http://localhost:11434/v1',
    model: 'llama3.2',
  },
};

export function AISettingsModal({ isOpen, onClose }: AISettingsModalProps) {
  const { aiSettings, setAISettings, importModelData, objective } = useBusinessStore();

  const [provider, setProvider] = useState<any>(aiSettings.provider || 'openai');
  const [apiKey, setApiKey] = useState(aiSettings.apiKey || '');
  const [baseUrl, setBaseUrl] = useState(
    aiSettings.baseUrl || PROVIDER_DEFAULTS.openai.baseUrl
  );
  const [model, setModel] = useState(
    aiSettings.model || PROVIDER_DEFAULTS.openai.model
  );

  const [promptText, setPromptText] = useState('');
  const [isGenerating, setIsGenerating] = useState(false);
  const [testStatus, setTestStatus] = useState<string | null>(null);
  const [aiError, setAiError] = useState<string | null>(null);

  // Draft model generated by AI (must be confirmed by user - PRD 7)
  const [draftModel, setDraftModel] = useState<{
    products: Product[];
    resources: Resource[];
    usage: UsageMatrix;
  } | null>(null);

  if (!isOpen) return null;

  const handleProviderChange = (newProvider: any) => {
    setProvider(newProvider);
    if (PROVIDER_DEFAULTS[newProvider]) {
      setBaseUrl(PROVIDER_DEFAULTS[newProvider].baseUrl);
      setModel(PROVIDER_DEFAULTS[newProvider].model);
    }
  };

  const handleSaveSettings = () => {
    setAISettings({
      provider,
      apiKey: apiKey.trim(),
      baseUrl: baseUrl.trim(),
      model: model.trim(),
    });
    setTestStatus('Pengaturan tersimpan!');
    setTimeout(() => setTestStatus(null), 2000);
  };

  // Text-to-Model Handler
  const handleGenerateModel = async () => {
    if (!promptText.trim()) return;
    setIsGenerating(true);
    setAiError(null);
    setDraftModel(null);

    try {
      if (!apiKey && provider !== 'ollama') {
        // Fallback local rule-based heuristic generation if no key provided
        setTimeout(() => {
          // Generate realistic bakery / custom draft
          const generatedProducts: Product[] = [
            { id: 'p1', name: 'Paket Standar', profit: 15000, unit: 'porsi', integerOnly: true },
            { id: 'p2', name: 'Paket Spesial', profit: 28000, unit: 'porsi', integerOnly: true },
          ];
          const generatedResources: Resource[] = [
            { id: 'r1', name: 'Bahan Pokok', capacity: 100, unit: 'kg', type: 'LEQ' },
            { id: 'r2', name: 'Waktu Pengerjaan', capacity: 40, unit: 'jam', type: 'LEQ' },
          ];
          const generatedUsage: UsageMatrix = {
            p1: { r1: 0.5, r2: 0.2 },
            p2: { r1: 1.2, r2: 0.4 },
          };

          setDraftModel({
            products: generatedProducts,
            resources: generatedResources,
            usage: generatedUsage,
          });
          setIsGenerating(false);
        }, 800);
        return;
      }

      // Call OpenAI-compatible endpoint
      const response = await fetch(`${baseUrl}/chat/completions`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${apiKey}`,
        },
        body: JSON.stringify({
          model,
          messages: [
            {
              role: 'system',
              content: `Anda adalah pakar pemodelan bisnis dan optimasi linier. Ubah deskripsi bisnis pengguna menjadi model terstruktur JSON tanpa teks pengantar.
Format JSON harus persis:
{
  "products": [
    {"id": "p1", "name": "string", "profit": number, "unit": "string", "integerOnly": boolean}
  ],
  "resources": [
    {"id": "r1", "name": "string", "capacity": number, "unit": "string", "type": "LEQ"}
  ],
  "usage": {
    "p1": {"r1": number}
  }
}`,
            },
            {
              role: 'user',
              content: promptText,
            },
          ],
          response_format: { type: 'json_object' },
        }),
      });

      if (!response.ok) {
        throw new Error(`Koneksi AI gagal (${response.status}: ${response.statusText})`);
      }

      const resData = await response.json();
      const content = resData.choices?.[0]?.message?.content;
      const parsed = JSON.parse(content);

      if (parsed.products && parsed.resources && parsed.usage) {
        setDraftModel(parsed);
      } else {
        throw new Error('Format keluaran AI tidak sesuai skema model.');
      }
    } catch (err: any) {
      setAiError(err.message || 'Gagal memproses draf AI. Periksa kembali kunci API dan URL.');
    } finally {
      setIsGenerating(false);
    }
  };

  const handleApplyDraft = () => {
    if (!draftModel) return;
    importModelData(objective, draftModel.products, draftModel.resources, draftModel.usage);
    setDraftModel(null);
    onClose();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-ink/40 backdrop-blur-sm p-4 overflow-y-auto animate-in fade-in">
      <div className="relative w-full max-w-2xl rounded-2xl border border-border bg-surface p-6 shadow-modal space-y-6 max-h-[90vh] overflow-y-auto">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-border pb-4">
          <div className="flex items-center gap-2">
            <Bot className="h-5 w-5 text-accent" />
            <h2 className="text-lg font-bold text-ink">
              Fitur AI Bisnis (Bawa Kunci Sendiri / BYOK)
            </h2>
          </div>
          <button
            onClick={onClose}
            className="rounded-lg p-1 text-ink-muted hover:bg-bg hover:text-ink min-touch-target"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* SECTION 1: TEXT-TO-MODEL PROMPT (PRD 7) */}
        <div className="space-y-3">
          <div className="flex items-center justify-between">
            <span className="text-xs font-bold text-accent">
              Text-to-Model (Buat Model Otomatis dari Cerita Usaha)
            </span>
            <span className="text-[11px] text-ink-muted">Draf harus dikonfirmasi</span>
          </div>

          <div className="relative">
            <textarea
              rows={3}
              value={promptText}
              onChange={(e) => setPromptText(e.target.value)}
              placeholder="Contoh: Saya punya usaha katering harian dengan menu Bento Ayam (untung Rp 12.000) dan Bento Sapi (untung Rp 20.000). Persediaan daging ayam 25 kg, daging sapi 15 kg, dan jam kerja staf dapur 30 jam per hari..."
              className="w-full rounded-xl border border-border bg-surface p-3 text-xs text-ink focus:border-accent focus:outline-none"
            />
            <button
              onClick={handleGenerateModel}
              disabled={isGenerating || !promptText.trim()}
              className="absolute right-2.5 bottom-3.5 flex items-center gap-1.5 rounded-lg bg-accent px-3 py-1.5 text-xs font-bold text-surface hover:bg-accent-hover disabled:opacity-50 transition-colors min-touch-target"
            >
              {isGenerating ? (
                <>
                  <Loader2 className="h-3.5 w-3.5 animate-spin" />
                  Merancang...
                </>
              ) : (
                <>
                  <Sparkles className="h-3.5 w-3.5" />
                  Buat Draf Model
                </>
              )}
            </button>
          </div>

          {aiError && (
            <div className="rounded-lg border border-status-infeasible-border bg-status-infeasible-light p-3 text-xs text-status-infeasible flex items-center gap-2">
              <AlertCircle className="h-4 w-4 shrink-0" />
              <span>{aiError}</span>
            </div>
          )}

          {/* DRAFT CONFIRMATION CARD (PRD 7) */}
          {draftModel && (
            <div className="rounded-xl border-2 border-accent bg-accent-light/40 p-4 space-y-3 animate-in fade-in">
              <div className="flex items-center justify-between">
                <span className="text-xs font-bold text-accent flex items-center gap-1.5">
                  <CheckCircle2 className="h-4 w-4" />
                  Draf Model Bisnis Ditemukan
                </span>
                <span className="text-[11px] text-ink-muted">
                  Periksa draf sebelum diterapkan
                </span>
              </div>

              <div className="text-xs text-ink space-y-1">
                <div>
                  <strong>Produk:</strong> {draftModel.products.map((p) => p.name).join(', ')}
                </div>
                <div>
                  <strong>Sumber Daya:</strong> {draftModel.resources.map((r) => r.name).join(', ')}
                </div>
              </div>

              <div className="flex items-center justify-end gap-2 pt-2 border-t border-accent-subtle">
                <button
                  onClick={() => setDraftModel(null)}
                  className="rounded-lg px-3 py-1.5 text-xs font-medium text-ink-muted hover:text-ink min-touch-target"
                >
                  Batalkan
                </button>
                <button
                  onClick={handleApplyDraft}
                  className="rounded-lg bg-accent px-4 py-1.5 text-xs font-bold text-surface hover:bg-accent-hover transition-colors min-touch-target"
                >
                  Terapkan ke Ruang Kerja Saya
                </button>
              </div>
            </div>
          )}
        </div>

        {/* SECTION 2: AI PROVIDER CONFIGURATION */}
        <div className="space-y-4 pt-4 border-t border-border">
          <div className="flex items-center justify-between">
            <span className="text-xs font-bold text-accent">
              Konfigurasi Kunci API (Bawa Kunci Sendiri)
            </span>
            <span className="text-[11px] text-status-optimal font-medium">
              Kunci tersimpan aman di peramban lokal
            </span>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            {/* Provider */}
            <div>
              <label className="block text-xs font-medium text-ink-muted mb-1">
                Penyedia AI
              </label>
              <select
                value={provider}
                onChange={(e) => handleProviderChange(e.target.value)}
                className="w-full rounded-lg border border-border bg-surface px-3 py-2 text-xs text-ink focus:border-accent focus:outline-none min-touch-target"
              >
                <option value="openai">OpenAI (GPT-4o / GPT-4o-mini)</option>
                <option value="groq">Groq Cloud (Llama 3.3 70B Cepat)</option>
                <option value="openrouter">OpenRouter (Banyak Model)</option>
                <option value="deepseek">DeepSeek (DeepSeek V3 / R1)</option>
                <option value="ollama">Ollama Lokal (100% Offline)</option>
              </select>
            </div>

            {/* API Key */}
            <div>
              <label className="block text-xs font-medium text-ink-muted mb-1">
                Kunci API (API Key)
              </label>
              <input
                type="password"
                value={apiKey}
                onChange={(e) => setApiKey(e.target.value)}
                placeholder="sk-..."
                className="w-full rounded-lg border border-border bg-surface px-3 py-2 text-xs text-ink focus:border-accent focus:outline-none min-touch-target"
              />
            </div>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            {/* Base URL */}
            <div>
              <label className="block text-xs font-medium text-ink-muted mb-1">
                Base URL
              </label>
              <input
                type="text"
                value={baseUrl}
                onChange={(e) => setBaseUrl(e.target.value)}
                className="w-full rounded-lg border border-border bg-surface px-3 py-2 text-xs text-ink focus:border-accent focus:outline-none min-touch-target"
              />
            </div>

            {/* Model Name */}
            <div>
              <label className="block text-xs font-medium text-ink-muted mb-1">
                Nama Model
              </label>
              <input
                type="text"
                value={model}
                onChange={(e) => setModel(e.target.value)}
                className="w-full rounded-lg border border-border bg-surface px-3 py-2 text-xs text-ink focus:border-accent focus:outline-none min-touch-target"
              />
            </div>
          </div>

          <div className="flex items-center justify-between pt-2">
            <span className="text-[11px] text-ink-muted">
              {apiKey ? 'Kunci terisi: Mode AI Aktif' : 'Kunci kosong: Mode Lokal Aktif (tanpa jaringan)'}
            </span>

            <div className="flex items-center gap-2">
              {testStatus && (
                <span className="text-xs font-semibold text-status-optimal">
                  {testStatus}
                </span>
              )}
              <button
                onClick={handleSaveSettings}
                className="rounded-lg bg-accent px-4 py-2 text-xs font-bold text-surface hover:bg-accent-hover transition-colors min-touch-target"
              >
                Simpan Pengaturan
              </button>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
